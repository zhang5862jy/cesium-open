// ============================================================================
// 血条网格生成器：一个单位四边形（quad）
// ============================================================================
// 血条是「广告牌式」的——始终面向屏幕，所以网格只需一个位于局部 XY 平面内的
// 矩形，由顶点着色器按相机右/上方向摆放即可。与其它工具一样，网格只上传
// 一次 GPU，之后不再改动，所有实例复用这同一份网格。

export interface QuadMesh {
  vertices: Float32Array;
  indices: Uint16Array;
}

/**
 * 构建以原点为中心、半边长 0.5 的单位四边形。
 *
 * 每个顶点只携带 2 个 float：corner（角坐标），范围 [-0.5, 0.5]。
 *   corner.x ∈ [-0.5, 0.5] —— 对应血条的水平方向（左 -> 右）
 *   corner.y ∈ [-0.5, 0.5] —— 对应血条的垂直方向（下 -> 上）
 *
 * 共 4 个顶点、2 个三角形（6 个索引）。
 */
export function createQuadMesh(): QuadMesh {
  // 四个角，顺序保证三角形逆时针（面向 +Z，即朝向屏幕观察者时可见）
  const vertices = new Float32Array([
    -0.5, -0.5, // 0：左下
    0.5, -0.5, //  1：右下
    0.5, 0.5, //   2：右上
    -0.5, 0.5, //  3：左上
  ]);

  // 两个三角形：(0,1,2) 与 (0,2,3)，均为逆时针
  const indices = new Uint16Array([0, 1, 2, 0, 2, 3]);

  return { vertices, indices };
}
